export const getSeed = (length: number = 3): string => {
  const seed: string[] = [];

  for (let i = 0; i < length; i++) {
    // Using Math.random and not seedrandom here to avoid repeated seeds
    const word = words[Math.floor(Math.random() * words.length)];

    seed.push(word);
  }

  return seed.join('-');
};
